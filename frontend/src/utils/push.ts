// DataVerse Web Push Notification Client Utilities

function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding)
    .replace(/-/g, '+')
    .replace(/_/g, '/');

  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);

  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export function isPushSupported(): boolean {
  return typeof window !== 'undefined' &&
    'serviceWorker' in navigator &&
    'PushManager' in window &&
    'Notification' in window;
}

export function getPushPermission(): NotificationPermission {
  if (!isPushSupported()) return 'denied';
  return Notification.permission;
}

export async function registerServiceWorker(): Promise<ServiceWorkerRegistration | null> {
  if (!isPushSupported()) return null;
  try {
    const reg = await navigator.serviceWorker.register('/arcade-sw.js?v=7', { 
      scope: '/',
      updateViaCache: 'none'
    });
    return reg;
  } catch (err) {
    console.warn('Service worker registration failed:', err);
    return null;
  }
}

export async function checkDevicePushSubscribed(): Promise<boolean> {
  if (!isPushSupported()) return false;
  try {
    const reg = await navigator.serviceWorker.getRegistration();
    if (!reg) return false;
    const sub = await reg.pushManager.getSubscription();
    return !!sub;
  } catch {
    return false;
  }
}

export async function autoSyncPushSubscription(token?: string | null): Promise<void> {
  if (!isPushSupported()) return;
  if (Notification.permission === 'granted') {
    await subscribeToPush(token);
  }
}

export async function subscribeToPush(token?: string | null): Promise<{ success: boolean; error?: string }> {
  if (!isPushSupported()) {
    return { success: false, error: 'Push notifications are not supported by this browser.' };
  }

  try {
    const permission = await Notification.requestPermission();
    if (permission !== 'granted') {
      return { success: false, error: 'Notification permission was denied or dismissed.' };
    }

    // 1. Ensure Service Worker is Active (REGISTER FIRST!)
    let registration = await navigator.serviceWorker.getRegistration();
    if (!registration) {
      registration = await navigator.serviceWorker.register('/arcade-sw.js?v=7', { 
        scope: '/',
        updateViaCache: 'none'
      });
    }

    // Wait until service worker is active/ready
    if (!registration.active) {
      await navigator.serviceWorker.ready;
    }

    // 2. Fetch VAPID Public Key from Backend
    const keyRes = await fetch('/api/push/vapid-public-key');
    if (!keyRes.ok) throw new Error('Failed to retrieve push authorization key');
    const { publicKey } = await keyRes.json();

    // 3. Get existing subscription or create a new one
    let subscription = await registration.pushManager.getSubscription();
    if (!subscription) {
      const applicationServerKey = urlBase64ToUint8Array(publicKey);
      subscription = await registration.pushManager.subscribe({
        userVisibleOnly: true,
        applicationServerKey: applicationServerKey as any
      });
    }

    const subJson = subscription.toJSON();
    if (!subJson.endpoint || !subJson.keys?.p256dh || !subJson.keys?.auth) {
      throw new Error('Invalid subscription keys generated by browser');
    }

    // 4. Save Subscription on Backend
    const headers: Record<string, string> = {
      'Content-Type': 'application/json'
    };
    if (token) {
      headers['Authorization'] = `Bearer ${token}`;
    }

    const saveRes = await fetch('/api/push/subscribe', {
      method: 'POST',
      headers,
      body: JSON.stringify({
        endpoint: subJson.endpoint,
        keys: {
          p256dh: subJson.keys.p256dh,
          auth: subJson.keys.auth
        },
        userAgent: navigator.userAgent
      })
    });

    if (!saveRes.ok) throw new Error('Failed to save push subscription in database');

    try {
      localStorage.setItem('dv_push_subscribed', 'true');
      localStorage.setItem('dv_push_endpoint', subJson.endpoint);
    } catch {}

    return { success: true };
  } catch (err: any) {
    console.error('Failed to subscribe to Web Push:', err);
    return { success: false, error: err.message || 'Failed to complete push subscription.' };
  }
}

export async function sendPushHeartbeat(): Promise<void> {
  if (!isPushSupported()) return;
  try {
    const endpoint = localStorage.getItem('dv_push_endpoint');
    if (!endpoint) return;

    await fetch('/api/push/heartbeat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ endpoint })
    });
  } catch {}
}
